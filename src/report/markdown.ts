import { SEVERITY_ORDER, type Finding, type ReviewResult, type Severity } from "../schema.js";

/** Hidden marker used to find and update our own PR comment. */
export const COMMENT_MARKER = "<!-- iac-pr-reviewer -->";

const BADGE_COLOR: Record<Severity, string> = { low: "brightgreen", medium: "yellow", high: "orange", critical: "red" };
const ICON: Record<Severity, string> = { low: "🟢", medium: "🟡", high: "🟠", critical: "🔴" };
const SOURCE_LABEL: Record<Finding["source"], string> = { precheck: "rule", llm: "AI", both: "rule + AI" };

export function renderMarkdown(r: ReviewResult, opts: { failOn?: Severity | "none" } = {}): string {
  const out: string[] = [COMMENT_MARKER];
  out.push(`## ${ICON[r.riskLevel]} Terraform plan review — risk: **${r.riskLevel.toUpperCase()}**`);
  out.push("");
  out.push(`![risk: ${r.riskLevel}](https://img.shields.io/badge/risk-${r.riskLevel}-${BADGE_COLOR[r.riskLevel]})`);
  out.push("");
  out.push(r.summary);
  out.push("");
  out.push(
    `**Plan:** ${r.stats.create} to create · ${r.stats.update} to update · ${r.stats.replace} to replace · ${r.stats.delete} to destroy` +
      (r.stats.moved ? ` · ${r.stats.moved} moved` : ""),
  );

  if (opts.failOn && opts.failOn !== "none" && SEVERITY_ORDER[r.riskLevel] >= SEVERITY_ORDER[opts.failOn]) {
    out.push("");
    out.push(`> [!CAUTION]\n> Risk level is at or above the configured threshold (\`${opts.failOn}\`); this check is failing.`);
  }

  const main = r.findings.filter((f) => f.severity !== "low");
  const minor = r.findings.filter((f) => f.severity === "low");

  if (!r.findings.length) {
    out.push("", "No risky changes found. ✅");
  } else {
    if (main.length) out.push("", `### Findings (${main.length})`, "", findingsTable(main));
    if (minor.length) {
      out.push("", `<details><summary>Low-severity findings (${minor.length})</summary>`, "", findingsTable(minor), "", "</details>");
    }
  }

  out.push("", "---");
  const llmNote = r.llm.ok
    ? `AI review by \`${r.llm.provider}/${r.llm.model}\``
    : r.llm.provider === "none"
      ? "AI review disabled; rule-based checks only"
      : r.llm.error === null
        ? "No resource changes, so no AI review was needed"
        : `⚠️ AI review unavailable (${escapeCell(r.llm.error)}); rule-based checks only`;
  out.push(`<sub>${llmNote} · generated by iac-pr-reviewer. AI findings can be wrong; verify before acting.</sub>`);
  return out.join("\n") + "\n";
}

function findingsTable(findings: Finding[]): string {
  const rows = findings.map(
    (f) =>
      `| ${ICON[f.severity]} ${f.severity} | \`${escapeCell(f.resource)}\` | ${escapeCell(f.issue)} | ${escapeCell(f.blastRadius)} | ${escapeCell(f.suggestion)} | ${SOURCE_LABEL[f.source]} |`,
  );
  return ["| Severity | Resource | Issue | Blast radius | Suggestion | Source |", "|---|---|---|---|---|---|", ...rows].join("\n");
}

function escapeCell(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
}
